const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const { createHash } = require('node:crypto');
const XLSX = require('../js/vendor/xlsx.full.min.js');

const ROOT = path.resolve(__dirname, '..');
const WORKBOOK = path.join(ROOT, 'data/bo-cau-hoi-kanji-n5-n4.xlsx');
const OUTPUT = path.join(ROOT, 'data/packs/question-supplement.pack.js');

const context = { window: {} };
vm.createContext(context);
vm.runInContext(fs.readFileSync(path.join(ROOT, 'js/kanji.js'), 'utf8'), context, { filename: 'js/kanji.js' });
const supported = new Set(Object.values(context.window.KANJI_DB.KANJI).map((info) => info.char));

const workbook = XLSX.read(fs.readFileSync(WORKBOOK), { type: 'buffer' });
const sourceRows = XLSX.utils.sheet_to_json(workbook.Sheets.Nguon, { defval: '' });
const clean = (value) => String(value || '').trim();
const promptText = (value) => clean(value).split(/\r?\n/, 1)[0];
const quizKey = (tier, word, sentence) => `${clean(tier)}\u0000${clean(word)}\u0000${clean(sentence)}`;

const triples = new Map();
for (const tier of ['N5', 'N4']) {
  const rows = XLSX.utils.sheet_to_json(workbook.Sheets[tier], { header: 1, defval: '' }).slice(1);
  for (let index = 0; index + 2 < rows.length; index += 3) {
    const group = rows.slice(index, index + 3);
    const word = clean(group[2][0]);
    if (!word) continue;
    const sentence = promptText(group[0][0]);
    const options = group.map((row) => row.slice(1, 5).map(clean));
    triples.set(quizKey(tier, word, sentence), {
      sentence,
      sentenceReading: promptText(group[1][0]),
      options,
    });
  }
}

const stableId = (value) => createHash('sha256').update(String(value)).digest('hex').slice(0, 20);
const challenges = [];
for (const row of sourceRows) {
  const tier = clean(row['Cấp độ']);
  const target = clean(row.Kanji);
  const word = clean(row['Từ ghép']);
  const answer = clean(row['Cách đọc']);
  const sentence = clean(row['Câu ví dụ']);
  if (!tier || !target || !word || !answer || !sentence || !supported.has(target)) continue;
  const triple = triples.get(quizKey(tier, word, sentence));
  if (!triple) throw new Error(`Không tìm thấy bộ câu hỏi ${tier}: ${target}/${word}/${sentence}`);
  for (const [mode, modeAnswer, options] of [
    ['m11', answer, triple.options[0]],
    ['m12', word, triple.options[1]],
    ['m6', answer, triple.options[2]],
  ]) {
    if (new Set(options).size !== 4 || options.filter((option) => option === modeAnswer).length !== 1) {
      throw new Error(`${tier} ${target}/${word} có options ${mode} không hợp lệ`);
    }
  }
  challenges.push({
    id: `workbook:v1:${tier.toLowerCase()}:${stableId(`${target}|${word}|${sentence}`)}`,
    tier,
    target,
    word,
    answer,
    wordReading: answer,
    mean: clean(row['Nghĩa Anh']),
    sentence,
    sentenceReading: triple.sentenceReading,
    sentenceMeaning: clean(row['Dịch tiếng Việt']),
    challengeOnly: true,
    options: { m6: triple.options[2], m11: triple.options[0], m12: triple.options[1] },
    sources: {
      vocabulary: clean(row['Nguồn từ vựng']),
      sentence: clean(row['Nguồn câu']),
      translation: clean(row['Nguồn dịch']),
      license: clean(row['Giấy phép']),
    },
  });
}

if (challenges.length !== 189) throw new Error(`Expected 189 supported challenges, found ${challenges.length}`);
const banner = `// Generated by scripts/sync-question-workbook.js from data/bo-cau-hoi-kanji-n5-n4.xlsx.\n// Do not edit this file by hand.\n`;
fs.writeFileSync(OUTPUT, `${banner}window.KanjiGOQuestionPack.register(${JSON.stringify(challenges, null, 2)});\n`);
console.log(`Wrote ${path.relative(ROOT, OUTPUT)} with ${challenges.length} challenges.`);
